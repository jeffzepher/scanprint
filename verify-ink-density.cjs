const fs=require('fs'),vm=require('vm'),assert=require('assert/strict');
const ctx={Uint8ClampedArray};vm.createContext(ctx);vm.runInContext(fs.readFileSync('processing-core.js','utf8'),ctx);
const w=240,h=200,data=new Uint8ClampedArray(w*h*4).fill(255);
const rect=(x0,y0,x1,y1,v)=>{for(let y=y0;y<y1;y++)for(let x=x0;x<x1;x++){const k=(y*w+x)*4;data[k]=data[k+1]=data[k+2]=v}};
rect(30,30,48,48,25);rect(80,30,98,48,110);rect(30,100,180,102,190);rect(30,145,180,147,240);
const run=options=>ctx.ScanCore.enhance(data,w,h,{mode:'text',...options}),out=run(),at=(a,x,y)=>a[(y*w+x)*4];
assert.ok(at(out,39,39)<25,'solid black center must not become hollow');
assert.ok(at(out,89,39)<160,'gray illustration interiors retain ink');
assert.ok(at(out,80,100)<180,'faint printed strokes retain contrast');
assert.ok(at(out,80,145)>245,'very weak show-through is suppressed');
assert.equal(at(out,200,160),255,'clean paper remains white');
const saver=run({inkSaver:true});assert.ok(at(saver,39,39)>at(out,39,39),'ink saving remains optional');
const bw=run({mode:'bw'});assert.equal(at(bw,39,39),0,'binary mode retains solid black');
const original=run({mode:'original'});assert.deepEqual(original,data,'original mode remains unchanged');
const natural=run({mode:'natural'}),naturalSaver=run({mode:'natural',inkSaver:true});assert.deepEqual(natural,naturalSaver,'ink saving does not alter natural mode');
console.log('PASS: solid black and gray interiors, faint print, weak show-through, white paper, optional ink saving, binary and original modes');
